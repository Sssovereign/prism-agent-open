// 统一错误协议（数据与接口.md：错误{error:{code,message,retryable,details?},requestId}）。
// details 只放可公开字段——不含路径、Key或原始headers，由调用方构造。

export type ErrorCode =
  // 400
  | 'VALIDATION_FAILED' | 'IDEMPOTENCY_CONFLICT' | 'REQUEST_IN_PROGRESS' | 'PROTOCOL_INVALID'
  // 401/403
  | 'AUTH_REQUIRED' | 'SESSION_EXPIRED' | 'CSRF_DENIED' | 'POLICY_DENIED'
  | 'TICKET_INVALID' | 'RESERVATION_INVALID'
  // 404
  | 'NOT_FOUND' | 'ARTIFACT_MISSING'
  // 403/409：更新屏障与切换流程
  | 'UPDATE_PENDING' | 'UPDATE_BARRIER_OPEN' | 'UPDATE_SNAPSHOT_FAILED'
  // 409
  | 'CONFIG_CHANGED' | 'INPUT_CHANGED' | 'WRITE_CONFLICT' | 'CURRENT_CONTENT_CHANGED'
  | 'RECONCILIATION_REQUIRED' | 'CONVERSATION_BUSY' | 'PROJECT_ARCHIVED' | 'MIGRATION_CHECKSUM_MISMATCH'
  | 'REQUEST_ALREADY_STARTED' | 'RUN_NOT_ACTIVE' | 'RUN_NOT_RESUMABLE' | 'WAIT_STATE_CHANGED'
  | 'RUN_STILL_ACTIVE' | 'WORKER_NOT_CLEANED'
  | 'ATTEMPT_NOT_ACTIVE' | 'WORKING_COPY_CONFLICT' | 'ARTIFACT_HASH_MISMATCH' | 'DELIVERY_INVALID_STATE'
  // 413
  | 'INPUT_TOO_LARGE'
  // 422
  | 'CREDENTIAL_REQUIRED' | 'MODEL_UNAVAILABLE' | 'DELIVERY_INVALID' | 'SANDBOX_UNAVAILABLE'
  | 'MODE_NOT_AVAILABLE' | 'CONTEXT_LIMIT_EXCEEDED' | 'SEARCH_NOT_CONFIGURED'
  // 422/5xx：内嵌浏览器（宿主不可用=桌面能力缺失；命令超时=页面/宿主卡顿）
  | 'BROWSER_UNAVAILABLE' | 'BROWSER_TIMEOUT' | 'BROWSER_FAILED'
  // 429
  | 'RESOURCE_BUSY' | 'PROVIDER_RATE_LIMIT' | 'MODEL_QUOTA_EXCEEDED'
  // 5xx
  | 'PROVIDER_ERROR' | 'TOOL_TIMEOUT' | 'MODEL_TIMEOUT' | 'INTERNAL_ERROR';

const STATUS_BY_CODE: Record<ErrorCode, number> = {
  VALIDATION_FAILED: 400, IDEMPOTENCY_CONFLICT: 409, REQUEST_IN_PROGRESS: 409, PROTOCOL_INVALID: 400,
  AUTH_REQUIRED: 401, SESSION_EXPIRED: 401, CSRF_DENIED: 403, POLICY_DENIED: 403,
  TICKET_INVALID: 401, RESERVATION_INVALID: 403,
  NOT_FOUND: 404, ARTIFACT_MISSING: 404,
  UPDATE_PENDING: 403, UPDATE_BARRIER_OPEN: 409, UPDATE_SNAPSHOT_FAILED: 500,
  CONFIG_CHANGED: 409, INPUT_CHANGED: 409, WRITE_CONFLICT: 409, CURRENT_CONTENT_CHANGED: 409,
  RECONCILIATION_REQUIRED: 409, CONVERSATION_BUSY: 409, PROJECT_ARCHIVED: 409, MIGRATION_CHECKSUM_MISMATCH: 409,
  REQUEST_ALREADY_STARTED: 409, RUN_NOT_ACTIVE: 409, RUN_NOT_RESUMABLE: 409, WAIT_STATE_CHANGED: 409,
  RUN_STILL_ACTIVE: 409, WORKER_NOT_CLEANED: 409,
  ATTEMPT_NOT_ACTIVE: 409, WORKING_COPY_CONFLICT: 409, ARTIFACT_HASH_MISMATCH: 409, DELIVERY_INVALID_STATE: 409,
  INPUT_TOO_LARGE: 413,
  CREDENTIAL_REQUIRED: 422, MODEL_UNAVAILABLE: 422, DELIVERY_INVALID: 422, SANDBOX_UNAVAILABLE: 422, MODE_NOT_AVAILABLE: 422,
  CONTEXT_LIMIT_EXCEEDED: 422, SEARCH_NOT_CONFIGURED: 422,
  BROWSER_UNAVAILABLE: 422, BROWSER_TIMEOUT: 504, BROWSER_FAILED: 500,
  RESOURCE_BUSY: 429, PROVIDER_RATE_LIMIT: 429, MODEL_QUOTA_EXCEEDED: 429,
  PROVIDER_ERROR: 502, TOOL_TIMEOUT: 504, MODEL_TIMEOUT: 504, INTERNAL_ERROR: 500,
};

const RETRYABLE_BY_DEFAULT: ReadonlySet<ErrorCode> = new Set<ErrorCode>([
  'RESOURCE_BUSY', 'PROVIDER_RATE_LIMIT', 'PROVIDER_ERROR', 'TOOL_TIMEOUT', 'MODEL_TIMEOUT', 'REQUEST_IN_PROGRESS',
]);

export function httpStatusOf(code: ErrorCode): number { return STATUS_BY_CODE[code]; }
export function retryableByDefault(code: ErrorCode): boolean { return RETRYABLE_BY_DEFAULT.has(code); }

/** 全部错误码运行时清单（由STATUS_BY_CODE的键保证与联合类型一一对应），供前端展示映射覆盖度测试。 */
export const ALL_ERROR_CODES = Object.keys(STATUS_BY_CODE) as readonly ErrorCode[];

export class ApiError extends Error {
  readonly code: ErrorCode;
  readonly details?: Record<string, unknown>;
  constructor(code: ErrorCode, message: string, details?: Record<string, unknown>) {
    super(message);
    this.code = code;
    this.details = details;
  }
  get status(): number { return httpStatusOf(this.code); }
  get retryable(): boolean { return retryableByDefault(this.code); }
}
